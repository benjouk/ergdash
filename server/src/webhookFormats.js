// appOrigin is passed in so the examples show the clickable-link behaviour
// exactly as this instance is configured.
export function webhookFormatDocs({ appOrigin = null } = {}) {
  return WEBHOOK_FORMAT_DOCS.map(doc => {
    const { headers, body } = buildWebhookRequest(doc.id, SAMPLE_NOTIFICATION, { appOrigin });
    return { ...doc, sample: { method: 'POST', headers, body } };
  });
}
